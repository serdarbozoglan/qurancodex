// Arabic slice: word-index window into the CLEANED verse. Never hand-typed.
function slice(id, from, to) {
  const v = BY_ID.get(id);
  if (!v) throw new Error('missing verse ' + id);
  const words = cleanArabicForDisplay(v.arabic).split(/\s+/).filter(Boolean);
  if (from === undefined) return words.join(' ');
  if (to > words.length) throw new Error(`slice out of range ${id} ${from}-${to} (len ${words.length})`);
  return words.slice(from, to).join(' ');
}

